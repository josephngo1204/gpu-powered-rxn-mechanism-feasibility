"""Atom-centred integration grids (spec §4 "Level of theory": (75,302), (99,590), (150,974)).

Radial quadrature: Becke's Gauss-Chebyshev (second kind) mapping
r = R (1 + x) / (1 - x), with R = Bragg-Slater radius, halved for every
element except hydrogen (A. D. Becke, J. Chem. Phys. 88, 2547 (1988)).
Weights integrate f(r) r^2 dr, which is cuEST's convention for radial weights.

Angular points are Lebedev grids, generated by cuEST; only the order is set here.
Atomic partitioning is done inside cuEST, so a cross-code comparison has to be
made in the converged-grid limit (spec §11).
"""

import math
import re
from dataclasses import dataclass

import numpy as np
import numpy.typing as npt

from saddle import units

FloatArray = npt.NDArray[np.float64]

# Lebedev-Laikov orders (V. I. Lebedev and D. N. Laikov, Dokl. Math. 59, 477 (1999)).
LEBEDEV_ORDERS = (
    6, 14, 26, 38, 50, 74, 86, 110, 146, 170, 194, 230, 266, 302, 350, 434, 590, 770,
    974, 1202, 1454, 1730, 2030, 2354, 2702, 3074, 3470, 3890, 4334, 4802, 5294, 5810,
)  # fmt: skip

# Bragg-Slater radii in angstrom (J. C. Slater, J. Chem. Phys. 41, 3199 (1964)),
# with Becke's 0.35 A for hydrogen and helium.
_BRAGG_SLATER_ANGSTROM = {
    "H": 0.35, "He": 0.35, "Li": 1.45, "Be": 1.05, "B": 0.85, "C": 0.70, "N": 0.65,
    "O": 0.60, "F": 0.50, "Ne": 0.45, "Na": 1.80, "Mg": 1.50, "Al": 1.25, "Si": 1.10,
    "P": 1.00, "S": 1.00, "Cl": 1.00, "Ar": 1.00, "K": 2.20, "Ca": 1.80, "Br": 1.15,
    "I": 1.40,
}  # fmt: skip


class GridError(ValueError):
    pass


def bragg_radius_bohr(symbol: str) -> float:
    try:
        return _BRAGG_SLATER_ANGSTROM[symbol] / units.BOHR_TO_ANGSTROM
    except KeyError as exc:
        raise GridError(f"no Bragg-Slater radius for {symbol}") from exc


def becke_midpoint_bohr(symbol: str) -> float:
    """Becke's radial scale: half the Bragg radius, except the full radius for H."""
    r = bragg_radius_bohr(symbol)
    return r if symbol == "H" else 0.5 * r


def becke_radial(n: int, scale_bohr: float) -> tuple[FloatArray, FloatArray]:
    """Nodes (bohr) and weights for int_0^inf f(r) r^2 dr, ordered from the nucleus out."""
    if n < 1 or not scale_bohr > 0:
        raise GridError("radial quadrature needs n >= 1 and a positive scale")
    i = np.arange(1, n + 1, dtype=np.float64)
    theta = i * math.pi / (n + 1)
    x = np.cos(theta)
    r = scale_bohr * (1.0 + x) / (1.0 - x)
    # Gauss-Chebyshev 2nd kind: int g(x) dx = sum pi/(n+1) sin^2(t) g(x)/sqrt(1-x^2)
    dr_dx = 2.0 * scale_bohr / (1.0 - x) ** 2
    w = math.pi / (n + 1) * np.sin(theta) * dr_dx * r * r
    order = np.argsort(r)
    return r[order], w[order]


@dataclass(frozen=True)
class GridSpec:
    radial: int
    angular: int

    def __post_init__(self) -> None:
        if self.radial < 1:
            raise GridError("a grid needs at least one radial point")
        if self.angular not in LEBEDEV_ORDERS:
            raise GridError(f"{self.angular} is not a Lebedev order")

    def __str__(self) -> str:
        return f"({self.radial},{self.angular})"


def parse_grid(text: str) -> GridSpec:
    m = re.fullmatch(r"\(\s*(\d+)\s*,\s*(\d+)\s*\)", text.strip())
    if m is None:
        raise GridError(f"grid must look like (radial,angular), got {text!r}")
    return GridSpec(int(m.group(1)), int(m.group(2)))
